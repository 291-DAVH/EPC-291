#!/usr/bin/env python3
"""Regenerate what a plugin says about its code from the code itself (stdlib only).

  python tools/build/regen_plugins.py            rewrite the generated fields of every plugin.json and the dependency section of its README
  python tools/build/regen_plugins.py --check    fail if any of them is out of date (the registry check runs this)

A plugin declares by hand only what it OWNS (`owns`: the engine packages it is the home of). Everything else is read from the imports of those packages:
  engine      the owned packages and every package they need, directly or not (what travels inside the plugin, under lib/)
  requires    the plugins that own the packages the owned ones import (the plugin graph is the import graph); plugins that own no code keep what they declare
  python      the third-party packages the packages in `engine` declare in their pyproject.toml
and the README gets a table: what it includes, what it needs, who needs it, and what to review if it changes.
"""
import argparse
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Set

sys.path.insert(0, str(Path(__file__).resolve().parent))
import impact_map as IM  # noqa: E402

REPO = IM.REPO
HUB = REPO / "claude" / "plugins"
START, END = "<!-- deps:start (generated by tools/build/regen_plugins.py) -->", "<!-- deps:end -->"


def load() -> Dict[str, dict]:
    return {m["id"]: m for m in IM.plugins().values()}


def engine_edges() -> Dict[str, Set[str]]:
    edges = IM.scan()[0]
    return {u: {t for t in ts if t in IM.ENGINE_ROOTS} for u, ts in edges.items() if u in IM.ENGINE_ROOTS}


def reach(units: List[str], edges: Dict[str, Set[str]]) -> Set[str]:
    seen: Set[str] = set(units)
    todo = list(units)
    while todo:
        for nxt in edges.get(todo.pop(), ()):
            if nxt not in seen:
                seen.add(nxt)
                todo.append(nxt)
    return seen


def owner_of(plugins: Dict[str, dict]) -> Dict[str, str]:
    return {u: pid for pid, m in plugins.items() for u in m.get("owns", [])}


def third_party(units: Set[str]) -> List[str]:
    """The third-party requirements the engine packages need (single source: their pyproject.toml), without the repository's own packages."""
    return sorted({d for u in units for d in IM.project_requirements(u)[0] if not d.startswith("epc-")})


def plugin_requires(pid: str, m: dict, plugins: Dict[str, dict], direct: Set[str], owners: Dict[str, str]) -> Dict[str, str]:
    """The plugins that own the packages this one imports, plus what it declares on plugins that own no code."""
    deps = {owners[t] for t in direct if t in owners and owners[t] != pid}
    kept = {d: r for d, r in m.get("requires", {}).items() if d in plugins and not plugins[d].get("owns")}
    return {**{d: f"^{plugins[d]['version']}" for d in sorted(deps)}, **kept}


def derived(pid: str, m: dict, plugins: Dict[str, dict], edges: Dict[str, Set[str]], owners: Dict[str, str]) -> dict:
    own = m.get("owns", [])
    if not own:
        return {}
    engine = sorted(reach(own, edges))
    direct = {t for u in own for t in edges.get(u, ()) if t not in own}
    return {"engine": engine, "requires": plugin_requires(pid, m, plugins, direct, owners), "python": {**m.get("python", {}), "requires": third_party(set(engine))}}


def impacted(pid: str, plugins: Dict[str, dict]) -> List[str]:
    users: Dict[str, Set[str]] = {}
    for q, m in plugins.items():
        for dep in m.get("requires", {}):
            users.setdefault(dep, set()).add(q)
    return sorted(IM.closure(pid, users))


def readme_block(pid: str, m: dict, plugins: Dict[str, dict], backend_users: Dict[str, Set[str]]) -> str:
    direct_users = sorted(q for q, x in plugins.items() if pid in x.get("requires", {}))
    modules = sorted({b for u in m.get("owns", []) for b in backend_users.get(u, ())})
    cells = lambda xs: ", ".join(f"`{x}`" for x in xs) or "—"                                  # noqa: E731
    return "\n".join([START, "## Dependencias", "",
                      "| | |", "|---|---|",
                      f"| Incluye (motor) | {cells(m.get('engine', []))} |",
                      f"| Es dueño de | {cells(m.get('owns', []))} |",
                      f"| Necesita (plugins) | {cells(sorted(m.get('requires', {})))} |",
                      f"| Lo necesitan | {cells(direct_users)} |",
                      f"| Paquetes de Python | {cells(m.get('python', {}).get('requires', []))} |",
                      f"| Si lo modificas, revisa | plugins {cells(impacted(pid, plugins))}; módulos del backend {cells(modules)} |", "",
                      "Generado por `python tools/build/regen_plugins.py`; el mapa completo está en `docs/architecture/DEPENDENCIAS.md`.", END])


def backend_users() -> Dict[str, Set[str]]:
    edges = IM.scan()[0]
    out: Dict[str, Set[str]] = {}
    for u, ts in edges.items():
        if u.startswith("backend."):
            for t in ts:
                out.setdefault(t, set()).add(u)
    return out


def _text(f: Path) -> str:
    return f.read_text(encoding="utf-8").replace("\r\n", "\n") if f.exists() else ""


def _readme(pid: str, new: dict, block: str) -> str:
    body = _text(HUB / pid / "README.md") or f"# {pid}\n\n{new.get('description', '')}\n"
    return re.sub(re.escape(START) + r".*?" + re.escape(END), block, body, flags=re.S) if START in body else body.rstrip() + "\n\n" + block + "\n"


def generate(plugins: Dict[str, dict]) -> Dict[str, Dict[Path, str]]:
    """Every file this tool owns, by plugin: path -> the text it must have."""
    edges, owners, users = engine_edges(), owner_of(plugins), backend_users()
    for pid, m in list(plugins.items()):
        plugins[pid] = {**m, **derived(pid, m, plugins, edges, owners)}
    return {pid: {HUB / pid / "plugin.json": json.dumps(new, indent=2, ensure_ascii=False) + "\n",
                  HUB / pid / "README.md": _readme(pid, new, readme_block(pid, new, plugins, users))} for pid, new in plugins.items()}


def apply(check: bool) -> int:
    files = generate(load())
    stale = sorted(pid for pid, fs in files.items() if any(_text(f) != t for f, t in fs.items()))
    if check:
        print("ERROR: out of date, run `python tools/build/regen_plugins.py`:", ", ".join(stale) if stale else "") if stale else print("plugins up to date")
        return 1 if stale else 0
    for fs in files.values():
        for f, t in fs.items():
            f.write_text(t, encoding="utf-8", newline="\n")
    print(f"plugins regenerated ({len(files)})")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    sys.exit(apply(ap.parse_args().check))
