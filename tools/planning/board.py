#!/usr/bin/env python3
"""Generate planning/BOARD.md from the front matter of epics and stories (stdlib only).

  python tools/planning/board.py            write planning/BOARD.md
  python tools/planning/board.py --check    exit 1 when BOARD.md is out of date or an item is invalid (for CI)

Front matter is a flat block of `key: value` lines between `---` markers; lists use `[a, b]`.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PLANNING = ROOT / "planning"
STATUSES = ["in-progress", "review", "ready", "backlog", "blocked", "done"]
PRIORITIES = {"P1", "P2", "P3"}
FIB = {1, 2, 3, 5, 8, 13, 21}


def front(path: Path):
    t = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---", t, re.S)
    if not m:
        return None
    out = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            out[k.strip()] = v.strip()
    return out


def load(folder):
    items = []
    for f in sorted((PLANNING / folder).glob("*.md")):
        fm = front(f)
        if fm:
            fm["_file"] = f.relative_to(PLANNING).as_posix()
            items.append(fm)
    return items


def validate(epics, stories):
    errs, eids = [], {e["id"] for e in epics}
    seen = set()
    for s in stories:
        if s["id"] in seen:
            errs.append(f"{s['id']}: duplicate id")
        seen.add(s["id"])
        if s.get("epic") not in eids:
            errs.append(f"{s['id']}: unknown epic {s.get('epic')}")
        if s.get("status") not in STATUSES:
            errs.append(f"{s['id']}: bad status {s.get('status')}")
        if s.get("priority") not in PRIORITIES:
            errs.append(f"{s['id']}: bad priority {s.get('priority')}")
        if s.get("estimate", "").isdigit() and int(s["estimate"]) not in FIB:
            errs.append(f"{s['id']}: estimate {s['estimate']} is not a story-point value")
        if s.get("status") in ("ready", "in-progress", "review", "done") and "## Acceptance criteria" not in (PLANNING / s["_file"]).read_text(encoding="utf-8"):
            errs.append(f"{s['id']}: no acceptance criteria")
    return errs


def points(items):
    return sum(int(i["estimate"]) for i in items if i.get("estimate", "").isdigit())


def render(epics, stories):
    L = ["# Board", "", "_Generated by `tools/planning/board.py`. Do not edit; edit the stories._", ""]
    done = [s for s in stories if s["status"] == "done"]
    L += [f"**{len(stories)} stories** · **{points(stories)} points** · done {len(done)} ({points(done)} pts) · "
          f"{round(100 * points(done) / max(1, points(stories)))}% of points", ""]
    L += ["## Epics", "", "| Epic | Title | Status | Stories | Done | Points |", "|---|---|---|---|---|---|"]
    for e in epics:
        es = [s for s in stories if s.get("epic") == e["id"]]
        ed = [s for s in es if s["status"] == "done"]
        L.append(f"| [{e['id']}]({e['_file']}) | {e['title']} | {e['status']} | {len(es)} | {len(ed)} | {points(es)} |")
    sprints = sorted({s.get("sprint", "-") for s in stories if s.get("sprint", "-") != "-"})
    for sp in sprints:
        ss = [s for s in stories if s.get("sprint") == sp]
        L += ["", f"## {sp}", "", f"{len(ss)} stories, {points(ss)} points, done {points([s for s in ss if s['status'] == 'done'])}", "",
              "| Story | Title | Epic | Priority | Pts | Status |", "|---|---|---|---|---|---|"]
        for s in ss:
            L.append(f"| [{s['id']}]({s['_file']}) | {s['title']} | {s['epic']} | {s['priority']} | {s.get('estimate', '')} | {s['status']} |")
    L += ["", "## Backlog by status (not in a sprint)", ""]
    for st in STATUSES:
        rows = [s for s in stories if s["status"] == st and s.get("sprint", "-") == "-"]
        if not rows:
            continue
        L += [f"### {st} ({len(rows)})", "", "| Story | Title | Epic | Priority | Pts |", "|---|---|---|---|---|"]
        for s in sorted(rows, key=lambda x: (x["priority"], x["id"])):
            L.append(f"| [{s['id']}]({s['_file']}) | {s['title']} | {s['epic']} | {s['priority']} | {s.get('estimate', '')} |")
        L.append("")
    return "\n".join(L).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    epics, stories = load("backlog/epics"), load("backlog/stories")
    errs = validate(epics, stories)
    for e in errs:
        print("ERROR:", e)
    text = render(epics, stories)
    board = PLANNING / "BOARD.md"
    if a.check:
        if errs or not board.exists() or board.read_text(encoding="utf-8") != text:
            print("BOARD.md is out of date or invalid" if not errs else "")
            return 1
        print("board OK")
        return 0
    board.write_text(text, encoding="utf-8", newline="\n")
    print(f"BOARD.md written: {len(epics)} epics, {len(stories)} stories, {points(stories)} points, {len(errs)} error(s)")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
