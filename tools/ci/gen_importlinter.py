"""Generate backend/.importlinter from the module layout (one contract set per module).

  python tools/ci/gen_importlinter.py           # (re)write backend/.importlinter
  python tools/ci/gen_importlinter.py --check   # fail when the file is out of date

Rules enforced (see docs/architecture):
  1. A module may import another module only through `epc.modules.<other>.public`.
  2. Inside a module the layers are api -> service -> repository (models at the bottom).
  3. `epc.core` never imports modules; engine packages never import `epc`.
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BACKEND = REPO / "backend"
MODULES = BACKEND / "src" / "epc" / "modules"
OUT = BACKEND / ".importlinter"
INTERNAL = ("api", "service", "repository", "models", "guard")     # never importable from another module
LAYERS = ("api", "service", "repository", "models")                # top -> bottom


# What may depend on what in the engine: a package imports only from the layers below it, never from a sibling in its own layer. This is what lets each one be taken alone.
ENGINE_LAYERS = ["epc_drawing", "epc_mld", "epc_sld", "epc_titleblock | epc_symbols | epc_plan | epc_calc", "epc_dxf"]


def engine_packages() -> list[str]:
    return sorted(p.name for src in (REPO / "engine").glob("*/src") for p in src.iterdir() if (p / "__init__.py").exists())


def module_names() -> list[str]:
    return sorted(p.name for p in MODULES.iterdir() if (p / "__init__.py").exists())


def engine_layers(engines: list[str]) -> list[str]:
    top_down = [l for l in ENGINE_LAYERS if all(x in engines for x in l.split(" | "))]
    return ["[importlinter:contract:engine-layers]", "name = engine: board design -> multi-line -> single-line -> symbols, title block, plan and calculation (each one installs on its own)",
            "type = layers", "layers =", *[f"    {l}" for l in top_down], ""]


def render() -> str:
    mods, engines = module_names(), engine_packages()
    out = ["# GENERATED by tools/ci/gen_importlinter.py -- do not edit by hand.", "[importlinter]",
           "root_packages =", "    epc", *[f"    {e}" for e in engines], "include_external_packages = False", ""]

    for m in mods:
        internals = [f"epc.modules.{m}.{i}" for i in INTERNAL if (MODULES / m / f"{i}.py").exists()]
        others = [f"epc.modules.{o}" for o in mods if o != m]
        if internals and others:
            out += [f"[importlinter:contract:{m}-encapsulated]", f"name = {m}: other modules use only its public interface",
                    "type = forbidden", "allow_indirect_imports = True", "source_modules =", *[f"    {o}" for o in others],
                    "forbidden_modules =", *[f"    {i}" for i in internals], ""]
        layers = [l for l in LAYERS if (MODULES / m / f"{l}.py").exists()]
        if len(layers) > 1:
            out += [f"[importlinter:contract:{m}-layers]", f"name = {m}: api -> service -> repository -> models", "type = layers",
                    "layers =", *[f"    epc.modules.{m}.{l}" for l in layers], ""]

    out += ["[importlinter:contract:modules-not-main]", "name = modules never import the composition root", "type = forbidden", "allow_indirect_imports = True",
            "source_modules =", "    epc.modules", "    epc.core", "forbidden_modules =", "    epc.main", "",
            "[importlinter:contract:core-independent]", "name = core is independent of modules", "type = forbidden", "allow_indirect_imports = True",
            "source_modules =", "    epc.core", "forbidden_modules =", "    epc.modules", ""]
    out += ["[importlinter:contract:engine-independent]", "name = engine packages never import the backend", "type = forbidden", "allow_indirect_imports = True",
            "source_modules =", *[f"    {e}" for e in engines], "forbidden_modules =", "    epc", ""]
    out += engine_layers(engines)
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur != text:
            print(f"{OUT} is out of date: run python tools/ci/gen_importlinter.py")
            return 1
        print("importlinter config up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
